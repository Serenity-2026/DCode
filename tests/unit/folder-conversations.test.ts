import { afterEach, expect, it, vi } from 'vitest'
import { existsSync, mkdirSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { DesktopService } from '../../src/main/services/desktop-service'
import { ElectronDesktop } from '../../src/main/infrastructure/electron-desktop'
import { StateRepository } from '../../src/main/repositories/state-repository'
import { contextMessages } from '../../src/shared/context'
import { create, cleanup, config } from './helpers'

const native = vi.hoisted(() => ({ getPath: vi.fn(), choose: vi.fn() }))
vi.mock('electron', () => ({ app: { getPath: native.getPath }, dialog: { showOpenDialog: native.choose } }))
afterEach(() => { vi.restoreAllMocks(); vi.clearAllMocks(); cleanup() })

it('selects a folder without reading its contents and leaves the filesystem unchanged on cancellation', async () => {
  const { directory } = await create(config, false)
  native.getPath.mockReturnValue(directory)
  const desktop = new ElectronDesktop(() => null)
  native.choose.mockResolvedValueOnce({ canceled: false, filePaths: [directory] })
  expect(await desktop.selectDirectory()).toBe(realpathSync(directory))
  expect(existsSync(join(directory, 'workspaces'))).toBe(false)
  const before = readdirSync(directory)
  native.choose.mockResolvedValue({ canceled: true, filePaths: [] })
  expect(await desktop.selectDirectory()).toBeNull()
  native.choose.mockResolvedValue({ canceled: false, filePaths: [] })
  expect(await desktop.selectDirectory()).toBeNull()
  native.choose.mockResolvedValue({ canceled: true, filePaths: [directory] })
  expect(await desktop.selectDirectory()).toBeNull()
  expect(native.getPath).not.toHaveBeenCalled()
  expect(readdirSync(directory)).toEqual(before)
})

it('does not save a conversation or change the active conversation when the chooser is cancelled', async () => {
  const { store, path, directory } = await create(config, false)
  const desktop = new DesktopService(store, new ElectronDesktop(() => null))
  native.choose.mockResolvedValue({ canceled: true, filePaths: [] })
  const save = vi.spyOn(StateRepository.prototype, 'save')
  const check = vi.spyOn(ElectronDesktop.prototype, 'checkDirectory')
  for (const active of [false, true]) {
    if (active) store.createConversation(directory)
    save.mockClear()
    const before = store.snapshot()
    const saved = readFileSync(path, 'utf8')
    expect(await desktop.createConversation()).toBeNull()
    expect(store.snapshot()).toEqual(before)
    expect(readFileSync(path, 'utf8')).toBe(saved)
    expect(save).not.toHaveBeenCalled()
    expect(check).not.toHaveBeenCalled()
  }
})

it('persists empty conversations, reuses their folder and checks account ownership and missing directories', async () => {
  const { store, auth, directory, path } = await create(config, false)
  const selected = join(directory, 'project')
  mkdirSync(selected)
  native.choose.mockResolvedValue({ canceled: false, filePaths: [selected] })
  const desktop = new DesktopService(store, new ElectronDesktop(() => null))
  const first = await desktop.createConversation()
  if (!first) throw new Error('应创建会话')
  const id = first.activeConversationId!
  expect(first.conversations[0]).toMatchObject({ directory: realpathSync(selected), title: '新对话', messages: [] })
  expect(new StateRepository(path).state.conversations[0]).toEqual(first.conversations[0])
  native.choose.mockClear()
  const second = await desktop.createConversation(id)
  if (!second) throw new Error('应复用目录创建会话')
  expect(native.choose).not.toHaveBeenCalled()
  expect(second.conversations).toHaveLength(2)
  expect(new Set(second.conversations.map(c => c.directory)).size).toBe(1)
  expect(second.activeConversationId).not.toBe(id)
  store.begin('第一问', false, 'test')
  expect(store.snapshot().conversations[1].title).toBe('第一问')
  expect(contextMessages(store.conversation(id))[0].content).toContain(realpathSync(selected))
  const broken = store.createConversation(join(directory, 'missing'))
  const before = store.snapshot()
  await expect(desktop.createConversation(broken.id)).rejects.toThrow('工作文件夹不存在')
  expect(store.snapshot()).toEqual(before)
  auth.logout()
  await auth.register({ username: 'another', password: 'another-password' })
  await expect(desktop.createConversation(id)).rejects.toThrow('会话不存在')
  expect(store.snapshot().conversations).toEqual([])
})

it('requires a directory-backed conversation before sending and rolls back a failed creation', async () => {
  const { store } = await create(config, false)
  expect(() => store.begin('问题', false, 'test')).toThrow('选择工作文件夹')
  expect(store.state.conversations).toHaveLength(0)
  vi.spyOn(StateRepository.prototype, 'save').mockImplementationOnce(() => { throw new Error('保存失败') })
  expect(() => store.createConversation('/workspace')).toThrow('保存失败')
  expect(store.state.activeConversationId).toBeNull()
  expect(store.state.conversations).toHaveLength(0)
})

it('deletes every conversation in an owned folder while keeping files and other accounts or paths', async () => {
  const { store, auth, directory, path } = await create(config, false)
  const project = join(directory, 'project')
  mkdirSync(project)
  const file = join(project, 'keep.txt')
  writeFileSync(file, '保留用户文件')
  const first = store.createConversation(project)
  store.createConversation(project)
  const other = store.createConversation(join(directory, 'other', 'project'))
  auth.logout()
  await auth.register({ username: 'another', password: 'another-password' })
  const privateConversation = store.createConversation(project)
  expect(() => store.apply({ type: 'folder:delete', id: first.id })).toThrow('会话不存在')
  auth.logout()
  await auth.login({ username: 'developer', password: 'test-password' })
  store.apply({ type: 'conversation:select', id: first.id })
  store.apply({ type: 'folder:delete', id: first.id })
  expect(store.snapshot().activeConversationId).toBeNull()
  expect(store.snapshot().conversations.map(c => c.id)).toEqual([other.id])
  expect(new StateRepository(path).state.conversations.map(c => c.id)).toEqual([other.id, privateConversation.id])
  expect(readFileSync(file, 'utf8')).toBe('保留用户文件')
})

it('rolls back an entire folder deletion when saving fails', async () => {
  const { store, directory, path } = await create(config, false)
  const first = store.createConversation(directory)
  store.createConversation(directory)
  const before = store.snapshot()
  const bytes = readFileSync(path, 'utf8')
  vi.spyOn(StateRepository.prototype, 'save').mockImplementationOnce(() => { throw new Error('保存失败') })
  expect(() => store.apply({ type: 'folder:delete', id: first.id })).toThrow('保存失败')
  expect(store.snapshot()).toEqual(before)
  expect(readFileSync(path, 'utf8')).toBe(bytes)
})

it('creates named projects in the application workspace or a selected parent without overwriting existing files', async () => {
  const { store, directory } = await create(config, false)
  native.getPath.mockReturnValue(directory)
  const desktop = new DesktopService(store, new ElectronDesktop(() => null))
  const first = await desktop.createProject({ name: '默认项目' })
  expect(first.conversations[0].directory).toBe(realpathSync(join(directory, 'workspaces', '默认项目')))
  const parent = join(directory, 'chosen')
  mkdirSync(parent)
  native.choose.mockResolvedValue({ canceled: false, filePaths: [parent] })
  expect(await desktop.selectProjectDirectory()).toBe(realpathSync(parent))
  const second = await desktop.createProject({ name: '新项目', parentDirectory: realpathSync(parent) })
  expect(second.conversations[1].directory).toBe(realpathSync(join(parent, '新项目')))
  writeFileSync(join(parent, '新项目', 'keep.txt'), '已有内容')
  await expect(desktop.createProject({ name: '新项目', parentDirectory: realpathSync(parent) })).rejects.toThrow('同名项目已存在')
  expect(readFileSync(join(parent, '新项目', 'keep.txt'), 'utf8')).toBe('已有内容')
  native.choose.mockResolvedValue({ canceled: true, filePaths: [] })
  expect(await desktop.selectProjectDirectory()).toBeNull()
  expect(store.snapshot().conversations).toHaveLength(2)
})

it('rejects invalid names and unselected or cross-account project locations before creating anything', async () => {
  const { store, auth, directory } = await create(config, false)
  native.getPath.mockReturnValue(directory)
  const desktop = new DesktopService(store, new ElectronDesktop(() => null))
  for (const name of ['', '../escape', '/absolute', 'path\\child', '..', 'NUL', 'COM1.txt', 'project.', 'a'.repeat(81)]) {
    await expect(desktop.createProject({ name })).rejects.toThrow()
  }
  await expect(desktop.createProject({ name: '未授权', parentDirectory: directory })).rejects.toThrow('先选择项目创建位置')
  native.choose.mockResolvedValue({ canceled: false, filePaths: [directory] })
  const parentDirectory = (await desktop.selectProjectDirectory())!
  auth.logout()
  await auth.register({ username: 'another', password: 'another-password' })
  await expect(desktop.createProject({ name: '其他账号', parentDirectory })).rejects.toThrow('先选择项目创建位置')
  expect(store.snapshot().conversations).toEqual([])
  expect(readdirSync(directory)).toEqual(['state.json'])
})
